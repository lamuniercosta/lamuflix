/// <reference types="node" />
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { describe, expect, it, vi } from 'vitest';
import {
  DEFAULT_TYPES_OUTPUT,
  SOURCE,
  generateTypes,
  renderHandlers,
  renderTypes,
} from '../../scripts/generate-api.mjs';
import { checkGenerated, filesMatch } from '../../scripts/check-api.mjs';

const METHOD_ORDER = ['get', 'post', 'put', 'patch', 'delete'];

async function readDocument() {
  return JSON.parse(await readFile(SOURCE, 'utf-8')) as {
    paths: Record<string, Record<string, { operationId: string }>>;
  };
}

describe('API generation scripts', () => {
  it('renders types deterministically with LF endings', async () => {
    // act
    const first = await renderTypes();
    const second = await renderTypes();

    // assert
    expect(first).toBe(second);
    expect(first).not.toContain('\r');
  });

  it('renders handlers deterministically with LF endings', async () => {
    // act
    const first = await renderHandlers();
    const second = await renderHandlers();

    // assert
    expect(first).toBe(second);
    expect(first).not.toContain('\r');
  });

  it('covers exactly the eighteen committed operations on a wildcard origin', async () => {
    // arrange
    const document = await readDocument();
    const expected: string[] = [];
    for (const [path, pathItem] of Object.entries(document.paths)) {
      for (const method of METHOD_ORDER) {
        if (pathItem[method]) {
          expected.push(`http.${method}('*${path.replace(/\{([^}]+)\}/g, ':$1')}'`);
        }
      }
    }

    // act
    const output = await renderHandlers();

    // assert
    expect(expected).toHaveLength(18);
    expect(output.match(/http\./g)).toHaveLength(18);
    for (const line of expected) {
      expect(output).toContain(line);
    }
    expect(output).not.toContain('http://');
    expect(output).not.toContain('https://');
  });

  it('compares generated bytes and rejects stale or missing content', async () => {
    // arrange
    const fresh = new TextEncoder().encode(await renderTypes());
    const stale = new TextEncoder().encode('// stale\n');

    // act + assert
    expect(filesMatch(fresh, fresh)).toBe(true);
    expect(filesMatch(stale, fresh)).toBe(false);
    expect(filesMatch(null, fresh)).toBe(false);
  });

  it('accepts the committed output and rejects a stale copy without overwriting it', async () => {
    // arrange
    const dir = await mkdtemp(join(tmpdir(), 'lamuflix-test-'));
    try {
      const stale = join(dir, 'stale.ts');
      await writeFile(stale, '// stale\n', 'utf-8');

      // act
      const committed = await checkGenerated(
        'src/api/types.ts',
        generateTypes,
        DEFAULT_TYPES_OUTPUT,
        join(dir, 'types.ts'),
      );
      const rejected = await checkGenerated(
        'stale fixture',
        generateTypes,
        stale,
        join(dir, 'stale-out.ts'),
      );

      // assert
      expect(committed).toBe(true);
      expect(rejected).toBe(false);
      expect(await readFile(stale, 'utf-8')).toBe('// stale\n');
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  });

  it('reads only the fixed committed openapi.json regardless of environment', async () => {
    // arrange
    vi.stubEnv('OPENAPI_SOURCE', 'https://example.invalid/openapi.json');

    // act
    const rendered = await renderTypes();
    const handlers = await renderHandlers();

    // assert
    expect(decodeURIComponent(SOURCE.pathname)).toMatch(/src\/api\/openapi\.json$/);
    expect(rendered).toBe(await readFile(DEFAULT_TYPES_OUTPUT, 'utf-8'));
    expect(handlers).not.toContain('example.invalid');

    vi.unstubAllEnvs();
  });
});
